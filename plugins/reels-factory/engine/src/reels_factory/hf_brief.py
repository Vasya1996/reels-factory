"""Задание агенту-сборщику композиции.

Монтаж — работа скилов HeyGen, а не наша. Раньше этот файл выдавал агенту
готовую пооконную раскадровку, и агент переставал быть режиссёром: он просто
перекладывал наш чертёж в HTML. Когда чертёж выходил пустым, пустым выходил и
ролик — при этом агент вёл себя безупречно, он выполнял написанное дословно.

Теперь мы сообщаем только то, чего агент знать не может: паспорт задания по
контракту фреймворка, материал, границы кадра и что вернуть. Где какая
вставка и как её обыграть — решает он через hyperframes-creative и каталог.
"""
from __future__ import annotations

from pathlib import Path

from reels_factory.config import FPS, OUT_H, OUT_W
from reels_factory.face_detect import free_bands
from reels_factory.hf_layout import avatar_gaps

# Manrope и Unbounded — единственные гарнитуры проекта, реально несущие
# кириллицу и (с донорским патчем в hf_fonts.py) казахские буквы в обоих
# регистрах. Montserrat/Inter (прежнее значение) не подходили: у Inter нет
# ни казахских букв, ни двенадцати заглавных русских; у Montserrat строчные
# казахские есть, заглавных нет — проверено fontTools.
FONTS = "Manrope, Unbounded"


def _scenario_block(block: dict) -> str:
    return (f'- **{block.get("role", "?")}** {float(block.get("start", 0)):g}–'
            f'{float(block.get("end", 0)):g} с: {block.get("speech", "")}')


def write_brief(rdir, *, scenario: dict, face: dict | None, duration: float,
                clips: list[dict] | None = None, language: str = "ru",
                retry_reason: str | None = None) -> Path:
    """Записать BRIEF.md рядом с материалом. Возвращает путь."""
    rdir = Path(rdir)
    rdir.mkdir(parents=True, exist_ok=True)

    blocks = "\n".join(_scenario_block(b) for b in scenario.get("blocks") or [])
    blocks = blocks or "Сценарий не передан."

    clips_block = "\n".join(
        f'- `{c["file"]}` — с {c["start"]:g} с, длительность {c["duration"]:g} с'
        for c in (clips or [])
    ) or "Клипов нет."

    gaps = avatar_gaps(clips or [], duration)
    gaps_block = "\n".join(
        f"- {a:g}–{b:g} с — ведущей в кадре нет, под пропуском чёрный кадр"
        for a, b in gaps
    ) or "- пропусков нет, ведущая в кадре весь ролик"

    bands = "\n".join(
        f'- left={b["left"]}, top={b["top"]}, width={b["width"]}, height={b["height"]}'
        for b in free_bands(face)
    ) or "- свободных полос нет: поверх ведущей текст не ставь"

    face_line = (
        f'Лицо ведущей: центр ({face["cx"]}, {face["cy"]}), высота головы '
        f'{face["h"]} px. Ничто поверх ведущей лицо не перекрывает. '
        "Полноэкранной графики это не касается — там ведущей нет."
        if face else "Лицо не найдено — считай запретной среднюю треть кадра."
    )

    retry_block = (
        f"\n## Повторная сборка\n\nПрошлая версия не прошла проверку:\n\n"
        f"{retry_reason}\n\nИсправь именно это.\n"
        if retry_reason else ""
    )

    text = f"""# Задание на сборку композиции
{retry_block}
## Паспорт задания

Поля контракта фреймворка. Первые восемь известны точно — бери как есть,
переспрашивать не у кого.

| Поле | Значение |
|---|---|
| `flow` | `automation` |
| `storyboard` | `no` |
| `mode` | `autonomous` |
| `destination` | вертикальный рилс: Reels, Shorts, TikTok |
| `aspect` | `1080x1920` |
| `length` | {duration:g} с, ровно |
| `language` | `{language}` |
| `narration` | `yes` — озвучка готова, лежит в `public/voice.wav` |

Оставшиеся три **выведи сам из сценария ниже** и запиши в план перед сборкой:

- `message` — одна фраза: что ролик обязан донести;
- `angle` — форма рассказа, из тех, что предлагает выбранный жанр;
- `audience` — кто это смотрит.

## Сценарий

Речь уже записана и разбита на блоки. Это единственный источник смысла:
монтаж строй от неё, а не от секунд.

{blocks}

## Материал (лежит в `public/`)

- клипы с ведущей, {OUT_W}×{OUT_H}, {FPS} кадров/с — расписание ниже
- `voice.wav` — **единственная аудиодорожка** ролика, источник истины по времени
- `words.json` — **готовые пословные тайминги**. Своё распознавание речи
  **не запускай**: оно даст худшую точность и работает по-английски.
- `vendor/gsap.min.js` — библиотека анимации локально

### Клипы с ведущей

Каждый ставится на своё время, со звуком выключенным: у видеоэлементов
`muted`, озвучка монтируется отдельным элементом.

{clips_block}

### Где ведущей нет

{gaps_block}

Эти интервалы закрывать целиком — иначе зритель увидит чёрный экран. Чем
закрывать, решаешь ты.

## Что ищешь сам

Вставок в папке нет намеренно. Подбирай их под смысл фраз скилом `media-use`,
его же командой (`media-use/SKILL.md:15`):

```
node <SKILL_DIR>/scripts/resolve.mjs --type image --project . \\
     --intent "<что должно быть на экране под эту фразу>"
```

Каталог отвечает настоящими фотографиями. Так же доступны `icon`, `bgm`,
`sfx`. Картинку под фразу **ищи, а не рисуй**: нарисованный вектор и подпись
вместо изображения вставкой не считаются, сборку это не пройдёт. Команда не
запустилась — разберись почему (`resolve.mjs --doctor` показывает причину за
минуту), а не подменяй результат своей графикой.

Готовые сцены бери из каталога (см. ниже), движение и переходы — через
`hyperframes-animation`. Ничего из этого мы за тебя не выбрали.

## Границы кадра

- {face_line}
- **Свободные полосы, если ставишь что-то поверх ведущей:**
{bands}
- **Сетка кадров:** любое время кратно 1/{FPS} секунды.
- **Стык поверх ведущей:** клип живёт на кадр дольше своего интервала, поэтому
  между такими элементами оставляй зазор не меньше 1/{FPS} секунды. К
  полноэкранной графике это не относится — там зазор недопустим.
- **Внешних ссылок нет.** Только локальные файлы.

## Шрифты

Стиль, раскладку и рамку выбираешь ты — так велит выбранный жанр. Мы
фиксируем только гарнитуры, и по технической причине: текст веди {FONTS}.

Файлы шрифтов **врезает движок** сам, после того как ты вернёшь композицию, и
врезает ровно те начертания, которые встретятся в `font-family` — объявлять
`@font-face` не нужно, но и писать имена гарнитур наугад нельзя.
Ссылок на внешние шрифты не пиши: у Manrope из Google Fonts нет казахских
букв, и отказ будет тихим.

## Субтитры

Пословные, по `words.json`: слово появляется ровно в свой `start`. Группы до
пяти слов, разрыв на знаке препинания от трёх. Под полноэкранной графикой
субтитры не ставь — они лезут поверх неё.

Субтитры — это `subtitles` в раскадровке, а не карточки. Группа слов карточкой
не считается и в `cards` не пишется.

## Блоки берём только из нашего каталога

Поле `registry` в `hyperframes.json` этой папки уже указывает на наш
отобранный каталог. Смотри, что там есть, и ставь оттуда:

```
hyperframes catalog --json
hyperframes add <имя-блока>
```

Общий каталог фреймворка в этом прогоне не используется: всё, что вернёт
команда, — уже только наше.

## Положение ведущей

За ролик оно обязано смениться: полный кадр, уменьшенное окно у края, полное
отсутствие с закадровым голосом. Где именно и в каком порядке — решаешь ты;
неподвижная ведущая на весь ролик не принимается.

## Планка монтажа

Ролик сверяют с эталонными рилсами, разобранными покадрово. Это не пожелания,
а то, по чему принимают. Где и чем добиться — твоё дело.

- Картинка меняется не реже раза в две секунды: склейка, замена вставки,
  выскочившая плашка — считается всё.
- Ни одного неподвижного плана длиннее восьми секунд. Держится ведущая дольше
  — поверх появляется плашка, ключевое слово или вставка.
- Неподвижной картинки в кадре не бывает: у вставки либо своё движение, либо
  медленный дрейф или наезд.
- Переходы жёсткие. Стык или «поп» за 0,15–0,3 с. Кроссфейдов и затемнений в
  эталонах нет ни одного.
- У титра есть второй слой акцента: подсветка слова, переезжающая по словам,
  либо ключевое слово вынесено отдельно и крупно.
- Положение ведущей меняется три-четыре раза за ролик, а уменьшенное окно
  двигается под раскладку, а не висит в одном углу.
- Первые секунды — крупный заголовок, набирающийся поверх ведущей. Финал —
  видимый объект призыва, а не фраза в титре.

## Что вернуть

1. `public/index.html` — собранная композиция.
2. `storyboard.json` — ровно в схеме `schemaVersion: 3` из `talking-head-recut`,
   без наших добавок: геометрия ведущей живёт в `videoTrack.bounds`, смысл
   карточки — в `intent` и `contentHints`, субтитры — в `subtitles`.

```json
{{"schemaVersion": 3,
  "composition": {{"fps": {FPS}, "width": {OUT_W}, "height": {OUT_H},
                  "durationSeconds": {duration:g}, "layout": "portrait",
                  "themeId": "noir", "seed": 42}},
  "videoTrack": {{"sourcePath": "clips/clip-00.mp4", "startSec": 0,
                 "endSec": {duration:g},
                 "bounds": {{"x": 0, "y": 0, "width": {OUT_W}, "height": {OUT_H}}}}},
  "subtitles": {{"enabled": true}},
  "cards": [
    {{"id": "card-01", "intent": "чем карточка держит зрителя",
      "startSec": 0.0, "endSec": 3.0, "accentIndex": 0, "zone": "video-overlay",
      "contentHints": {{"kicker": "…", "title": "…", "detail": "…"}}}}
  ]}}
```

Число и темп карточек считай формулой плотности из `talking-head-recut`
(базовый темп по длительности × плотность речи, минимум пять) — она там
описана, своего не придумывай.
"""
    path = rdir / "BRIEF.md"
    path.write_text(text, encoding="utf-8")
    return path
