            "генерации, а это главные деньги ролика. Секунды складывает код "
            "по полю `presenter`: всё, что не `none`, считается временем "
            "аватара.\n"
            "\n"
            "1. Сцена без биролла — аватар во весь кадр (`full` или "
            "`punch`).\n"
            "2. Сцена с бироллом — `presenter: \"none\"`.\n"
            "3. `pip-*` — когда диктор обращается к зрителю: «я», «мы», «ты», "
