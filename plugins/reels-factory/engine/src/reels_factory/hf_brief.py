"""Задание агенту-сборщику композиции.

Монтажные решения принимает скил HeyGen. Наше дело — сообщить то, чего он
знать не может: вертикальный формат, наш стиль, безопасные полосы, где лицо,
какие тайминги истина и ЧТО показывать. Всё числами, без «сделай красиво».
"""
from __future__ import annotations

from pathlib import Path

from reels_factory.config import FPS, OUT_H, OUT_W
from reels_factory.face_detect import free_bands

STYLE_NAME = "minimal"
FONTS = "Montserrat, Inter"


def _window_block(window: dict, text_by_id: dict, faceless: bool = False) -> str:
    timing = window.get("final_timing") or {}
    effect = window.get("effect") or {}
    variables = (effect.get("hyperframes") or {}).get("variables") or {}
    speech = " ".join(text_by_id.get(pid, "") for pid in window.get("phrase_ids") or [])

    lines = [
        f'### Окно `{window.get("id")}` — {timing.get("start")}–{timing.get("end")} с',
        f'- зона-подсказка от плана: `{window.get("zone")}` (можешь выбрать другую)',
        *(["- **ведущей в кадре нет**: зона обязательно `fullscreen`, "
           "интервал закрыт целиком, без дыр"] if faceless else []),
        f'- что звучит: «{speech.strip()}»',
        *(["- субтитры на этом интервале скрыты"]
          if window.get("caption") == "hidden" else []),
    ]
    if effect.get("type") and effect["type"] != "none":
        lines.append(f'- тип вставки: `{effect["type"]}`')
    block = (effect.get("hyperframes") or {}).get("block")
    if block:
        lines.append(f"- готовый блок: `{block}`")
    title = variables.get("title") or effect.get("title")
    if title:
        lines.append(f"- заголовок: «{title}»")
    items = [str(x) for x in (variables.get("items") or []) if isinstance(x, str)]
    if items:
        lines.append("- пункты: " + "; ".join(f"«{i}»" for i in items))
    if effect.get("type") in (None, "none"):
        lines.append("- вставки нет: показывай ведущую, карточку не рисуй")
    return "\n".join(lines)


def write_brief(rdir, plan: dict, *, face: dict | None, duration: float,
                clips: list[dict] | None = None, media: list[dict] | None = None,
                retry_reason: str | None = None) -> Path:
    """Записать BRIEF.md рядом с материалом. Возвращает путь."""
    rdir = Path(rdir)
    rdir.mkdir(parents=True, exist_ok=True)

    text_by_id = {p["id"]: p.get("text", "") for p in plan.get("phrases") or []}
    # «ведущей нет» — свойство блока, а не окна: тот же признак, что у гейта
    faceless_blocks = {b["index"] for b in (plan.get("blocks") or [])
                       if b.get("avatar_required") is False}
    windows = "\n\n".join(
        _window_block(w, text_by_id,
                      faceless=w.get("block_index") in faceless_blocks)
        for w in plan.get("windows") or []) or "Окон нет."

    bands = "\n".join(
        f'- left={b["left"]}, top={b["top"]}, width={b["width"]}, height={b["height"]}'
        for b in free_bands(face)
    ) or "- свободных полос нет: карточки не ставь"

    face_line = (
        f'**Лицо ведущей:** центр ({face["cx"]}, {face["cy"]}), высота головы '
        f'{face["h"]} px. Карточка, стоящая поверх ведущей, лицо не перекрывает. '
        "Полноэкранных карточек это правило не касается — там ведущей нет."
        if face else "Лицо не найдено — считай запретной среднюю треть кадра."
    )

    clips_block = "\n".join(
        f'- `{c["file"]}` — с {c["start"]:g} с, длительность {c["duration"]:g} с'
        for c in (clips or [])
    ) or "Клипов нет."

    media_block = "\n".join(
        f'- `{item["file"]}` → окно `{item["window_id"]}`: {item["what"]}'
        for item in (media or [])
    ) or "Материала нет."

    retry_block = (
        f"\n## Повторная сборка\n\nПрошлая версия не прошла проверку:\n\n"
        f"{retry_reason}\n\nИсправь именно это.\n"
        if retry_reason else ""
    )

    text = f"""# Задание на сборку композиции
{retry_block}
## Что надо сделать

Собрать композицию, в которой:

1. Клипы с ведущей стоят на таймлайне по расписанию ниже, каждый в своё время.
   Склеивать их не надо, движок ставит несколько кусков на одну дорожку сам.
   По умолчанию видео занимает весь кадр; если раскладка карточки его двигает
   или ужимает — укажи в раскадровке `videoRect` этой карточки, иначе проверка
   лица посчитает по устаревшей геометрии и завернёт сборку.
2. `voice.wav` — **единственная аудиодорожка** композиции. Звук самих клипов
   выключен: у видеоэлементов `muted`, дорожка монтируется отдельным элементом.
3. **Пословные субтитры** построены по `words.json`: слово появляется ровно в свой
   `start`. Группы до пяти слов, разрыв на знаке препинания от трёх. **Там, где у
   окна ниже стоит пометка «субтитры скрыты», их быть не должно** — под
   полноэкранной графикой они лишние и лезут поверх неё.
4. Поверх этого — графические карточки по окнам плана (раздел «Что показывать»).

Без пунктов 1–3 ролик не примут: без звука падает нормализация громкости,
без субтитров — проверка соответствия речи.

## Материал (лежит в public/)

- клипы с ведущей, {OUT_W}×{OUT_H}, {FPS} кадров/с — расписание в разделе «Клипы»
- `voice.wav` — единая озвучка, источник истины по времени
- `words.json` — **готовые пословные тайминги**. Своё распознавание речи **не запускай**:
  оно даст худшую точность и работает по-английски.
- `vendor/gsap.min.js` — библиотека анимации локально

## Формат

Холст {OUT_W}×{OUT_H}, {FPS} кадров/с, общая длительность ровно {duration:g} с.

## Клипы с ведущей

Каждый ставится на своё время, во весь кадр, со звуком выключенным.
Где клипа нет — там ведущей в кадре нет намеренно, и это место закрывает
полноэкранная карточка.

{clips_block}

## Стиль

Стиль `{STYLE_NAME}` из библиотеки стилей скила, один на весь ролик. Шрифты —
{FONTS}: только они содержат кириллицу и казахские ә ғ қ ң ө ұ ү һ і. Шрифты из
комплекта скила кириллицы не содержат. Подключай их именем семейства в
`font-family` — движок сам встроит их при компиляции. Ссылок на шрифты не пиши.

## Раскладка и зоны

Раскладки и зоны — твои, как описано в скиле: четыре раскладки, пять зон.
Выбирай для каждой карточки по смыслу момента.

Правило выбора одно и оно продуктовое: **ведущая в кадре там, где работает
лицо** — хук, вывод, призыв, эмоция; **кадр отдан показу там, где важнее
показать** — перечисление, число, сравнение, демонстрация. Во втором случае
ставь зону `fullscreen`: ведущей там нет намеренно, и её видео на этот кусок
не заказано.

## Жёсткие границы

- {face_line}
- **Свободные полосы, если ставишь карточку поверх ведущей:**
{bands}
- **Сетка кадров:** любое время карточки кратно 1/{FPS} секунды.
- **Стык карточек поверх ведущей:** клип живёт на кадр дольше своего окна, поэтому
  между такими карточками оставляй зазор не меньше 1/{FPS} секунды. К полноэкранным
  карточкам это не относится — там зазор недопустим, см. следующий пункт.
- **Окна без ведущей закрываются целиком.** Если у окна ниже стоит пометка
  «ведущей в кадре нет», её интервал обязан быть покрыт полноэкранными карточками
  от начала до конца — одной или цепочкой подряд, без дыр. Аватар на этот кусок не
  заказан, под карточкой чёрный кадр: любая дыра — чёрный экран у зрителя.
- **Ритм: не оставляй экран без событий дольше 3 секунд** (кроме первых
  4 секунд — там хук, ведущая работает лицом, и карточки не нужны).
  Событие — карточка в любой зоне. Материал для окон-дыр уже приготовлен
  и перечислен в разделе «Материал для вставок» — используй его.
- **Внешних ссылок нет.** Только локальные файлы.

## Что показывать по окнам

Содержание задано планом монтажа. Не придумывай своё и не добавляй предметов,
которых нет в тексте окна.

{windows}

## Материал для вставок

{media_block}

## Что вернуть

1. `public/index.html` — собранная композиция.
2. `storyboard.json`. Формат скила сохраняй, но **добавь в каждую карточку поле
   `contentRect`** — прямоугольник видимого содержимого в пикселях, и, если
   раскладка двигает или ужимает видео, поле `videoRect` — куда поставлено окно
   с ведущей. По этим двум проверяется лицо; без `contentRect` сборка не
   принимается, `videoRect` по умолчанию считается полным кадром.

```json
{{"cards": [
  {{"id": "card-01", "startSec": 0.0, "endSec": 3.0, "zone": "video-overlay",
    "contentRect": {{"left": 130, "top": 980, "width": 810, "height": 260}},
    "videoRect": {{"left": 0, "top": 0, "width": 1080, "height": 1920}}}}
]}}
```
"""
    path = rdir / "BRIEF.md"
    path.write_text(text, encoding="utf-8")
    return path
