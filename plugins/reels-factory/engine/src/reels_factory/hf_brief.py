"""Задание агенту-сборщику: он режиссирует, композицию собирает код.

Первая версия этого файла выдавала агенту готовую пооконную раскадровку — агент
переставал быть режиссёром. Вторая отдала ему всё, включая изготовление: он
верстал `index.html` целиком. Третья оставила ему фрагменты карточек — и это
всё ещё было 42 тысячи токенов на выходе, то есть четверть часа прогона.
Четвёртая давала ему каталог наших полноэкранных блоков, и кадр из них выходил
слайд-шоу: пустые две трети, оставшиеся заглушки, недоигравшие анимации.

Здесь он не пишет разметку вовсе и блоков не выбирает. Кадр собран слоями —
ведущая, поверх неё вставка, поверх всего титр, — и решения агента ровно три на
сцену: какие фразы она накрывает, где в кадре ведущая и что показать вставкой.
Изготовление целиком у кода: секунды, геометрия, подбор файла, субтитры,
сборка композиции.
"""
from __future__ import annotations

from pathlib import Path

from reels_factory.config import FPS, OUT_H, OUT_W
from reels_factory.hf_gates import min_scenes
from reels_factory.hf_layout import avatar_gaps
from reels_factory.hf_phrases import MIN_SCENE, faceless_phrases
from reels_factory.hf_rhythm import MAX_STATIC_SPAN

# Manrope и Unbounded — единственные гарнитуры проекта, реально несущие
# кириллицу и (с донорским патчем в hf_fonts.py) казахские буквы в обоих
# регистрах.
FONTS = "Manrope, Unbounded"

#: Маршрут, который исполняет сборку. Роутер `/hyperframes` читает его из шапки
#: BRIEF.md и дальше не переспрашивает («`BRIEF.md` exists → Read `workflow` and
#: `flow`», hyperframes/SKILL.md:28; ключ описан в
#: hyperframes-core/references/brief-format.md:13).
#:
#: Не `talking-head-recut`: его контракт — «Existing talking-head... footage to
#: package. The underlying clip plays unchanged»
#: (hyperframes/references/routes/talking-head-recut.md:3). Мы клип ведущей
#: режем на острова, часть ролика идёт вовсе без неё и закрывается вставкой —
#: это «custom edit», и роутер такой случай отправляет сюда сам: «Retiming,
#: reordering... remixing footage is a custom edit and falls through to
#: `/general-video`» (hyperframes/SKILL.md:67).
WORKFLOW = "general-video"

#: Положения ведущей и что каждое значит для агента. Словаря позиций у них нет
#: ни в `/general-video`, ни в блоках реестра — это наше. Механизм родной:
#: обычный клип, которому таймлайн меняет геометрию обёртки
#: (hyperframes-creative/references/composition-patterns.md:11-14).
POSITIONS = [
    ("full", "во весь кадр", "вставки в этой сцене быть не может — её некуда "
     "поставить"),
    ("punch", "во весь кадр, наездом крупнее", "то же самое, но заметно ближе: "
     "это «поп» для ударной реплики"),
    ("pip-tr", "в окошке справа сверху", "кадр занимает вставка, ведущая поверх "
     "неё"),
    ("pip-tl", "в окошке слева сверху", "то же"),
    ("pip-br", "в окошке справа снизу", "то же"),
    ("pip-bl", "в окошке слева снизу", "то же"),
    ("stack", "в верхней части кадра", "вставка занимает нижнюю"),
    ("none", "её в кадре нет", "вставка занимает весь кадр"),
]


def _scenario_block(block: dict) -> str:
    return f'- **{block.get("role", "?")}**: {block.get("speech", "")}'


def _phrase_line(phrase: dict, faceless: set[int]) -> str:
    """Строка фразы для задания.

    Длина нужна, чтобы агент не назначал сцену на фразу короче минимума: код
    такую сцену дотянет за счёт соседней, и картинка съедет с реплики.
    """
    length = float(phrase["end"]) - float(phrase["start"])
    mark = "  ← **ведущей тут нет**" if phrase["id"] in faceless else ""
    return (f'- `{phrase["id"]}` **{phrase["role"]}** {length:.1f} с — '
            f'{phrase["text"]}{mark}')


def _positions_block() -> str:
    return "\n".join(f"- `{name}` — {what}; {note}" for name, what, note
                     in POSITIONS)


def write_brief(rdir, *, scenario: dict, face: dict | None, duration: float,
                clips: list[dict] | None = None, language: str = "ru",
                retry_reason: str | None = None,
                phrases: list[dict] | None = None) -> Path:
    """Записать BRIEF.md рядом с материалом. Возвращает путь."""
    rdir = Path(rdir)
    rdir.mkdir(parents=True, exist_ok=True)

    blocks = "\n".join(_scenario_block(b) for b in scenario.get("blocks") or [])
    blocks = blocks or "Сценарий не передан."

    phrases = phrases or []
    faceless = set(faceless_phrases(phrases, clips or [], duration))
    phrases_block = "\n".join(_phrase_line(p, faceless) for p in phrases) or (
        "Фразы не размечены.")
    last_phrase = (phrases or [{"id": 0}])[-1]["id"]

    gaps = avatar_gaps(clips or [], duration)
    if faceless:
        gaps_block = (
            "На эти фразы аватар не заказан — ведущей в кадре нет физически:\n"
            + "\n".join(f"- фраза `{pid}`" for pid in sorted(faceless))
            + "\n\nСцены, накрывающие эти фразы, обязаны стоять с `presenter: "
              '"none"` и нести вставку. Иначе там чёрный экран.')
    else:
        gaps_block = "Ведущая в кадре весь ролик."

    low = min_scenes(duration)

    retry_block = (
        f"\n## Повторная сборка\n\nПрошлая версия не прошла проверку:\n\n"
        f"{retry_reason}\n\nИсправь именно это.\n"
        if retry_reason else ""
    )

    text = f"""---
workflow: {WORKFLOW}
flow: automation
storyboard: no
destination: reels
aspect: {OUT_W}x{OUT_H}
language: {language}
length: {duration:g}s
narration: yes
---

# Задание на монтаж рилса
{retry_block}
Ты режиссёр монтажа. Композицию **собирает код**. Разметку ты не пишешь ни
строки: ни `index.html`, ни сцен, ни таймлайна, ни субтитров. Твой ответ —
один файл `storyboard.json`.

## Паспорт задания

Шапка выше — подтверждённый бриф, вопросов по нему не задавай. Из `flow` и
`storyboard` выводится `mode: autonomous`. `destination` — вертикальный рилс:
Reels, Shorts, TikTok. `length` — {duration:g} с ровно. `narration: yes` —
озвучка готова и лежит в `public/voice.wav`.

Поле `workflow` названо, чтобы ты знал жанр, но **конвейер этого маршрута в
данном проходе не исполняется**: ни устанавливать его, ни входить в него, ни
проходить его шаги не надо. От тебя нужен только план — всё остальное делает
код после тебя.

## Сценарий

Речь уже записана. Это единственный источник смысла: монтаж строй от неё.

{blocks}

## Из чего собран кадр

Кадр — это слои, а не череда непрозрачных экранов:

1. **вставка** — фотография, подобранная по твоему описанию;
2. **ведущая** — клип, поверх вставки, в том месте кадра, которое ты назвал;
3. **титр** — пословные субтитры, идут весь ролик поверх всего.

Ролик нарезан на **сцены**. Сцена — это кусок озвучки плюс два решения: где в
этом куске ведущая и что показано вставкой. Сцены идут подряд и покрывают всю
озвучку: промежутков не бывает, каждая фраза принадлежит ровно одной сцене.

## Фразы озвучки

Речь разбита на пронумерованные фразы. **Секунд в ответе быть не должно** —
сцена называет фразы, на которые приходит, а когда именно и сколько она стоит,
считает код по звуку.

Сцена короче {MIN_SCENE:g} с в кадре читается вспышкой. Если фраза короткая,
отдай сцене две-три подряд.

{phrases_block}

## Материал (лежит в `public/`)

- клипы с ведущей, {OUT_W}×{OUT_H}, {FPS} кадров/с
- `voice.wav` — **единственная аудиодорожка** ролика, источник истины по времени
- `words.json` — пословные тайминги. Своё распознавание речи **не запускай**.

### Где ведущей нет

{gaps_block}

## Где ведущая

Значение поля `presenter`. Оно же решает, куда встанет вставка, — второй раз
это называть не надо:

{_positions_block()}

Положение ведущей — твой главный ритмический инструмент. За ролик оно обязано
смениться **не меньше трёх раз**, и меряется это по готовому файлу.

## Что показать вставкой

Поле `insert`: либо `null`, либо объект с одним полем `look` — что должно быть
на экране, словами.

Вставка — всегда **настоящая фотография сцены из жизни**, снятая камерой.
Значки, пиктограммы, логотипы и знаки не годятся: подбор отдаёт их прозрачным
файлом, а вставка занимает весь кадр — сквозь прозрачное будет виден чёрный
экран. Проверено прогоном 14: шесть вставок из четырнадцати пришли прозрачными,
и весь финал ролика вышел чёрным.

Пиши предметно, называя предмет и обстановку: «стопка исписанных листов со
скриптами продаж крупным планом» находится, «символ порядка» — нет.

Вставка иллюстрирует реплику, которую диктор произносит в эти самые фразы:
бери предмет из её слов. Говорит «запишите три вопроса» — в кадре рука пишет
список, а не «бизнесмен в офисе» вообще.

Текста на вставке не бывает: весь текст ролика несёт титр. Подбор отсеет
файлы с надписями и водяными знаками сам.

**Вставка обязательна не меньше чем в трёх сценах.** Проверка ищет подобранный
файл в композиции и без него сборку заворачивает.

## Что делает код, а не ты

- **Все секунды.** Начало и конец каждой сцены, сетку кадров, предел в
  {MAX_STATIC_SPAN:g} с держит код. Считать это в уме не надо.
- **Геометрию.** Куда встанет окно ведущей и какой прямоугольник займёт
  вставка, считается по названному тобой положению.
- **Разметку.** Слои композиции ставит код.
- **Субтитры.** Пословный титр строится по `words.json` их готовым компонентом.
  В план субтитры не пиши и в сцены не превращай.
- **Подбор вставок.** Ты называешь словами, что должно быть на экране; ищет и
  подставляет файл код.

## Ритм

Темп задают правила твоего же маршрута, чисел мы не назначаем.

- Их правило жанра: в быстром вертикальном ролике **одна мысль живёт в кадре
  1,5–4 секунды**. Сцены разной длины лучше метронома: короткие на
  перечислениях, длинные на главной мысли. Число сцен выбирай под смысл.
- Сцен не меньше {low} — иначе найдётся кусок длиннее {MAX_STATIC_SPAN:g} с
  без смены картинки.
- **Соседние сцены обязаны отличаться картинкой.** Две подряд с одинаковым
  положением ведущей и одинаковой вставкой — это один план, а не два: детектор
  их не разделит. Меняй либо положение, либо вставку.
- Ни одна сцена не длиннее {MAX_STATIC_SPAN:g} с.
- Открывай ролик ведущей во весь кадр: первая секунда — это лицо, а не картинка.
- Перед кульминацией хороша сцена-передышка: ведущая крупно, без вставки —
  тишина, на фоне которой удар прозвучит. Несколько спокойных сцен на ролик —
  это правильно, энергия обязана меняться.
- Финал — видимый объект призыва, а не фраза в титре.

## Биты

Каждой сцене — поле `beat`: её место в рассказе. Переходы, вспышку и движение
вставок по битам собирает код, в плане о них больше ничего не нужно.

- `hook` — первая сцена, открытие.
- `point` — обычная точка рассказа; таких большинство.
- `turn` — поворот к новой части рассказа. Ставь там, где меняется тема,
  обычно один-три на ролик.
- `climax` — кульминация, самая сильная реплика. На её стыке код даёт вспышку
  со свушем. **Ровно одна на ролик**, и не в первые две секунды.
- `outro` — финал, последняя сцена: мягкое растворение.

## Чего в кадре не бывает

- Служебных надписей и рубрик («вопрос первый», «фото из каталога»,
  пояснений о самом ролике): всё, что зритель читает, — это титр, а он
  строится из самой озвучки.
- Стоковых клише: рукопожатие в переговорной, «бизнесмен вообще», абстрактные
  кубики и градиенты ни о чём.
- Текста и водяных знаков на фотографиях: подбор их отсеивает, но и не проси
  картинку с надписью.
- Значков, эмодзи и рисованной графики вместо фотографий.

## Что вернуть

Один файл `storyboard.json`. Ничего больше не создавай.

```json
{{"message": "главная мысль ролика одной фразой",
 "audience": "кто это смотрит, одной фразой",
 "angle": "форма рассказа: как ты ведёшь зрителя от первой фразы к последней",
 "arc": "Хук → Проблема → Решение → Доказательство → Призыв",
 "scenes": [
    {{"id": "s-01", "intent": "чем сцена держит зрителя", "beat": "hook",
      "phrases": [0, 0], "presenter": "full", "insert": null,
      "avatarNeeded": true}},
    {{"id": "s-02", "intent": "…", "beat": "point", "phrases": [1, 2],
      "presenter": "pip-br",
      "insert": {{"look": "стопка исписанных листов со скриптами продаж",
                 "kind": "photo"}},
      "avatarNeeded": true}},
    {{"id": "s-03", "intent": "…", "beat": "turn", "phrases": [3, 3],
      "presenter": "none",
      "insert": {{"look": "пустой переговорный стол в утреннем свете",
                 "kind": "photo"}},
      "avatarNeeded": false}}
  ]}}
```

`phrases` — номера первой и последней фразы сцены, из списка выше (есть фразы
`0`–{last_phrase}). Диапазоны идут по возрастанию, встык, без пропусков: первая
сцена начинается с фразы `0`, последняя кончается фразой `{last_phrase}`.

`avatarNeeded` — нужна ли ведущая на этом куске вообще. Сейчас это поле никто не
читает; оно готовит следующий шаг, где аватар перестанут заказывать там, где его
не видно. Ставь `false` там, где ведущей в кадре нет и по смыслу она не нужна.

`message`, `audience` и `angle` заполни сам, у клиента их не спрашивай: их
контракт велит вывести из материала — «Infer when clear», «Derive and echo one
sentence», «Recommend one route-defined option»
(hyperframes-core/references/brief-contract.md:71-73). Главная мысль нужна не
для отчёта: без неё нечем сверять, та ли картинка встала в сцену.

## Чего не делать

- Не пиши HTML, CSS и JavaScript. Ни файла, ни строки.
- Не запускай их CLI: ни `hyperframes check`, ни `preview`, ни `render`, ни
  `add`. Проверки идут после тебя.
- Оформление и сборка композиции в этом прогоне не твои.
  Их справочники по темам, стилям и раскладкам не открывай — время ограничено.
- Не подбирай картинки сам и не запускай распознавание речи.
- **Не считай секунды.** Ни `startSec`, ни `endSec`, ни длительностей в ответе
  быть не должно — код их не примет. Не открывай `words.json` и не пересчитывай
  тайминги питоном: всё о времени сказано номерами фраз.
- Шрифты — {FONTS}, объявлять их не нужно.

Ничего не спрашивай, все решения принимай сам.
"""
    path = rdir / "BRIEF.md"
    path.write_text(text, encoding="utf-8")
    return path
