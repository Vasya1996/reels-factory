"""Задание агенту-сборщику композиции.

Монтаж — работа скилов HeyGen, а не наша. Раньше этот файл выдавал агенту
готовую пооконную раскадровку, и агент переставал быть режиссёром: он просто
перекладывал наш чертёж в HTML. Когда чертёж выходил пустым, пустым выходил и
ролик — при этом агент вёл себя безупречно, он выполнял написанное дословно.

Теперь мы сообщаем только то, чего агент знать не может: паспорт задания по
контракту фреймворка, материал, границы кадра и что вернуть. Где какая
вставка и как её обыграть — решает он через hyperframes-creative и каталог.
"""
from __future__ import annotations

from pathlib import Path

from reels_factory.config import FPS, OUT_H, OUT_W
from reels_factory.face_detect import free_bands

STYLE_NAME = "minimal"
# Manrope и Unbounded — единственные гарнитуры проекта, реально несущие
# кириллицу и (с донорским патчем в hf_fonts.py) казахские буквы в обоих
# регистрах. Montserrat/Inter (прежнее значение) не подходили: у Inter нет
# ни казахских букв, ни двенадцати заглавных русских; у Montserrat строчные
# казахские есть, заглавных нет — проверено fontTools.
FONTS = "Manrope, Unbounded"


def _scenario_block(block: dict) -> str:
    return (f'- **{block.get("role", "?")}** {float(block.get("start", 0)):g}–'
            f'{float(block.get("end", 0)):g} с: {block.get("speech", "")}')


def _avatar_gaps(clips: list[dict], duration: float) -> list[tuple[float, float]]:
    """Интервалы, где клипа с ведущей нет.

    Ведущую заказывают кусками — там, где она нужна по смыслу. Под пропуском
    чёрный кадр, поэтому агент обязан знать эти интервалы: закрыть их — его
    работа, а не наша. Считаем от клипов, а не от плана монтажа: клипы это
    факт, план — чужое мнение.
    """
    covered = sorted((float(c["start"]), float(c["start"]) + float(c["duration"]))
                     for c in clips or [])
    gaps, cursor = [], 0.0
    for start, end in covered:
        if start - cursor > 1.0 / FPS:
            gaps.append((cursor, start))
        cursor = max(cursor, end)
    if duration - cursor > 1.0 / FPS:
        gaps.append((cursor, duration))
    return gaps


def write_brief(rdir, *, scenario: dict, face: dict | None, duration: float,
                clips: list[dict] | None = None, language: str = "ru",
                retry_reason: str | None = None) -> Path:
    """Записать BRIEF.md рядом с материалом. Возвращает путь."""
    rdir = Path(rdir)
    rdir.mkdir(parents=True, exist_ok=True)

    blocks = "\n".join(_scenario_block(b) for b in scenario.get("blocks") or [])
    blocks = blocks or "Сценарий не передан."

    clips_block = "\n".join(
        f'- `{c["file"]}` — с {c["start"]:g} с, длительность {c["duration"]:g} с'
        for c in (clips or [])
    ) or "Клипов нет."

    gaps = _avatar_gaps(clips or [], duration)
    gaps_block = "\n".join(
        f"- {a:g}–{b:g} с — ведущей в кадре нет, под пропуском чёрный кадр"
        for a, b in gaps
    ) or "- пропусков нет, ведущая в кадре весь ролик"

    bands = "\n".join(
        f'- left={b["left"]}, top={b["top"]}, width={b["width"]}, height={b["height"]}'
        for b in free_bands(face)
    ) or "- свободных полос нет: поверх ведущей текст не ставь"

    face_line = (
        f'Лицо ведущей: центр ({face["cx"]}, {face["cy"]}), высота головы '
        f'{face["h"]} px. Ничто поверх ведущей лицо не перекрывает. '
        "Полноэкранной графики это не касается — там ведущей нет."
        if face else "Лицо не найдено — считай запретной среднюю треть кадра."
    )

    retry_block = (
        f"\n## Повторная сборка\n\nПрошлая версия не прошла проверку:\n\n"
        f"{retry_reason}\n\nИсправь именно это.\n"
        if retry_reason else ""
    )

    text = f"""# Задание на сборку композиции
{retry_block}
## Паспорт задания

Поля контракта фреймворка. Первые восемь известны точно — бери как есть,
переспрашивать не у кого.

| Поле | Значение |
|---|---|
| `flow` | `automation` |
| `storyboard` | `no` |
| `mode` | `autonomous` |
| `destination` | вертикальный рилс: Reels, Shorts, TikTok |
| `aspect` | `1080x1920` |
| `length` | {duration:g} с, ровно |
| `language` | `{language}` |
| `narration` | `yes` — озвучка готова, лежит в `public/voice.wav` |

Оставшиеся три **выведи сам из сценария ниже** и запиши в план перед сборкой:

- `message` — одна фраза: что ролик обязан донести;
- `angle` — форма рассказа, из тех, что предлагает выбранный жанр;
- `audience` — кто это смотрит.

## Сценарий

Речь уже записана и разбита на блоки. Это единственный источник смысла:
монтаж строй от неё, а не от секунд.

{blocks}

## Материал (лежит в `public/`)

- клипы с ведущей, {OUT_W}×{OUT_H}, {FPS} кадров/с — расписание ниже
- `voice.wav` — **единственная аудиодорожка** ролика, источник истины по времени
- `words.json` — **готовые пословные тайминги**. Своё распознавание речи
  **не запускай**: оно даст худшую точность и работает по-английски.
- `vendor/gsap.min.js` — библиотека анимации локально

### Клипы с ведущей

Каждый ставится на своё время, со звуком выключенным: у видеоэлементов
`muted`, озвучка монтируется отдельным элементом.

{clips_block}

### Где ведущей нет

{gaps_block}

Эти интервалы закрывать целиком — иначе зритель увидит чёрный экран. Чем
закрывать, решаешь ты.

## Что ищешь сам

Вставок в папке нет намеренно. Подбирай их под смысл фраз через `media-use`:

```
resolve --type image --intent "<что должно быть на экране под эту фразу>"
```

Так же доступны `icon`, `bgm`, `sfx`. Готовые сцены и оформление бери из
каталога через `hyperframes-registry`, движение и переходы — через
`hyperframes-animation`. Ничего из этого мы за тебя не выбрали.

## Границы кадра

- {face_line}
- **Свободные полосы, если ставишь что-то поверх ведущей:**
{bands}
- **Сетка кадров:** любое время кратно 1/{FPS} секунды.
- **Стык поверх ведущей:** клип живёт на кадр дольше своего интервала, поэтому
  между такими элементами оставляй зазор не меньше 1/{FPS} секунды. К
  полноэкранной графике это не относится — там зазор недопустим.
- **Внешних ссылок нет.** Только локальные файлы.

## Стиль и шрифты

Стиль `{STYLE_NAME}`, один на весь ролик. Текст веди гарнитурами {FONTS}.

Файлы шрифтов **врезает движок** сам, после того как ты вернёшь композицию —
объявлять `@font-face` не нужно. Ссылок на внешние шрифты не пиши: у Manrope
из Google Fonts нет казахских букв, и отказ будет тихим.

## Субтитры

Пословные, по `words.json`: слово появляется ровно в свой `start`. Группы до
пяти слов, разрыв на знаке препинания от трёх. Под полноэкранной графикой
субтитры не ставь — они лезут поверх неё.

## Что вернуть

1. `public/index.html` — собранная композиция.
2. `storyboard.json`. Формат скила сохраняй, но **добавь в каждую карточку поле
   `contentRect`** — прямоугольник видимого содержимого в пикселях, и, если
   раскладка двигает или ужимает видео, поле `videoRect` — куда поставлено окно
   с ведущей. По этим двум проверяется лицо; без `contentRect` сборка не
   принимается, `videoRect` по умолчанию считается полным кадром.

```json
{{"cards": [
  {{"id": "card-01", "startSec": 0.0, "endSec": 3.0, "zone": "video-overlay",
    "contentRect": {{"left": 130, "top": 980, "width": 810, "height": 260}},
    "videoRect": {{"left": 0, "top": 0, "width": 1080, "height": 1920}}}}
]}}
```
"""
    path = rdir / "BRIEF.md"
    path.write_text(text, encoding="utf-8")
    return path
