def _open_rule(avatar_ordered: bool) -> str:
    """Правило открытия — теми же двумя мерками, какими его судят.

    Гейт до заказа требует ОДНОВРЕМЕННО полнокадрового положения и заказанной
    ведущей (`D28_avatar_bookends`, hf_render.py), а правило называло только
    положение. Связь «`none` там, где `avatarNeeded: false`» подана в другом
    разделе и в одну сторону — буквальный читатель обратную не выведет, и план
    с `presenter: "full"` при `avatarNeeded: false` проходил мимо правила прямо
    в отказ.
    """
    rule = ("- Открывай ролик ведущей во весь кадр: первая сцена — `full` или "
            "`punch`,\n  первая секунда — это лицо.")
    if avatar_ordered:
        return rule
    return (rule + " Ей же ставь `avatarNeeded: true`: без заказа\n  ведущей "
            "на этих секундах не будет, и полный кадр останется пустым.")


