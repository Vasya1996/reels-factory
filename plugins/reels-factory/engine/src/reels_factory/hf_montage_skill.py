def number(value: float) -> str:
    """Число секунд в тексте для агента: одно написание на оба файла.

    До этого одна и та же величина печаталась тремя способами — «1,5–4
    секунды», «2.2 с», «4.0 с», — и три написания читаются как три разных
    единицы. Их канон требует конкретных единиц, а не разнобоя
    (claude-prompting-best-practices). Десятая доля — вся точность, которая
    тут осмысленна: сетка кадров мельче не бывает.
    """
    text = f"{float(value):.1f}"
    if text.endswith(".0"):
        text = text[:-2]
    return text.replace(".", ",")


def seconds(value: float) -> str:
    """Секунды с единицей: «2,4 с», «3 с». Единственная форма записи времени."""
    return f"{number(value)} с"


