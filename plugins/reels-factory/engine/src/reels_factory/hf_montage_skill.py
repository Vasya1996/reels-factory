"""Монтажная доктрина — скиллом в рабочей папке, а не текстом задания.

Правила выбора кадра (положения ведущей, серии вставок, пять форм схем, ритм)
одинаковы от ролика к ролику: это знание, а не данные прогона. Их место —
скилл, который агент читает сам: «a skill's body loads only when it's used, so
long reference material costs almost nothing until you need it»
(code.claude.com/docs/en/skills). Проектные скиллы подхватываются из
`.claude/skills/` стартовой папки и всех родительских, а стартуем мы в рабочей
папке прогона (`hf_agent.py`), поэтому файл кладём туда же.

Задание остаётся тем, чем должно: данными этого ролика и контрактом ответа.
До этой развилки доктрина занимала три четверти BRIEF.md и читалась целиком в
каждом прогоне, включая повторный.
"""
from __future__ import annotations

from pathlib import Path

SKILL_NAME = "reels-montage"

#: Имя и описание — по их правилу: третье лицо, «что делает + когда
#: применять», описание решает, сработает ли скилл вовсе
#: (platform.claude.com/docs/en/agents-and-tools/agent-skills/best-practices).
#: Задание вдобавок ссылается на файл прямо, поэтому срабатывание не зависит
#: от одного описания.
DESCRIPTION = (
    "Монтажные правила вертикального рилса: где в кадре ведущая, чем занять "
    "кадр (видео-вставка или схема), какие бывают формы схем и их границы, "
    "ритм и биты рассказа. Применять при планировании storyboard.json для "
    "рилса по заданию BRIEF.md."
)


def _body(*, positions: str, form_floors: str, icon_names: str,
          series_min: float, series_max: float, face_gap: float,
          max_static: float) -> str:
    return f"""# Монтаж вертикального рилса

Правила выбора кадра. Данные этого ролика — фразы озвучки, материал, что
сказал заказчик — лежат в `BRIEF.md` рядом; формат ответа тоже там.

## Из чего собран кадр

Кадр — это слои, а не череда непрозрачных экранов:

1. **фон** — цвет и свечение из `frame.md`, виден там, где его не закрывают
   остальные слои;
2. **вставка** — видео, найденное по твоему запросу;
3. **ведущая** — клип поверх вставки, в том месте кадра, которое ты назвал;
4. **титр** — пословные субтитры, идут весь ролик поверх всего.

Ролик нарезан на **сцены**. Сцена — это кусок озвучки плюс два решения: где в
этом куске ведущая и что показано в кадре. Сцены идут подряд и покрывают всю
озвучку: каждая фраза принадлежит одной сцене.

Кадр держит одно из двух — вставка либо схема. Сверх этого сцена может нести
плашку (`overlay`), а сцена без ведущей — значок (`icon`). Сцена, где нет ни
ведущей, ни вставки, ни схемы, ни значка, ни плашки, показывает фон с титром и
читается обрывом рассказа.

## Где ведущая

Значение поля `presenter`. Оно же решает, куда встанет вставка:

{positions}

Выбор положения:

1. Сцена без вставки — `full` или `punch`: ведущая закрывает кадр сама.
2. Сцена со вставкой — `pip-*` (ведущая уголком поверх вставки) или `stack`
   (ведущая сверху, вставка снизу). При схеме бери нижний уголок: схема
   занимает верхнюю треть кадра.
3. `pip-*` уместнее, когда диктор обращается к зрителю: говорит «я», «мы»,
   «ты», «смотри» или задаёт вопрос.
4. `stack` — когда вставка показывает предмет, который диктор называет в этих
   же фразах.
5. `none` — только на фразах, помеченных в задании «без ведущей».

Ведущая уже снята: на каждой фразе без такой пометки её клип куплен и оплачен
заказчиком, поэтому там она должна быть в кадре — зритель должен её увидеть.

За ролик ведущая должна побывать в трёх разных окнах, не считая `none`:
`full` и `punch` — уже два разных окна, второе заметно крупнее.

<examples>
<example>«Ответы клиентам, письма, анализ документов», вставки нет → `full`: держать нечем, кроме лица, а реплика перечислительная и спокойная</example>
<example>«Если хочешь, покажу, как создать» → `pip-br`: диктор обращается к зрителю, лицо в этот момент важнее вставки</example>
<example>«Вот этот переключатель», вставка: палец на переключателе → `stack`: названный предмет виден в кадре целиком, а не уголком</example>
<example>«…нейросеть запоминает один раз», вставка: руки на клавиатуре → `pip-tr`: диктор говорит о механизме, а не о зрителе и не о предмете в кадре, поэтому ни `pip-br`, ни `stack` не напрашиваются — берём верхний уголок, и ведущая остаётся видна поверх вставки</example>
</examples>

## Что показать вставкой

Поле `insert`: либо `null`, либо объект с двумя полями — `shots` (список из
двух поисковых запросов ПО-АНГЛИЙСКИ, уходят в сток как есть) и
`kind: "video"`.

Вставка входит в кадр серией из двух планов: одиночная читается случайным
кадром, два плана про одно и то же — это монтаж. Сцену на два плана делит код
по паузе внутри неё, шов — тоже его работа, тебе нужны два запроса.

Два плана — про одну мысль, но разными кадрами: общий и деталь, предмет и
рука, действие и результат. Одинаковые запросы дадут два одинаковых кадра.

Вставка — живое действие, снятое камерой. Запрос пиши как действие с
предметом, 3–7 слов: «hand writing checklist in notebook», «fingers flipping
through documents closeup». Абстракция вроде «order symbol» не найдётся.
Выводи запрос из реплики этих самых фраз: говорит «запишите три вопроса» —
«hand writing list in notebook», а не «businessman in office» вообще.

Стоковые клише — рукопожатие в переговорной, «бизнесмен вообще», абстрактные
кубики — читаются заглушкой; пиши конкретное действие.

Называй моментов под вставку больше, чем нужно: от пяти до восьми на ролик.
Часть код снимет — две серии подряд он не ставит, между ними держится
{face_gap:.1f} с лица. Пять и больше дают ему выбор, при котором ритм ролика
сохранится. Лишние он уберёт сам, и это не ошибка плана.

Сцена под серию живёт {series_min:g}–{series_max:g} секунды: в более короткой
два плана мелькнут, в более длинной застынут.

Кандидатов после поиска отбирает отдельный судья: твоя работа — точный запрос
и честная реплика, а не подбор файла.

## Ритм и биты

Сцены разной длины держат зрителя лучше метронома: короткие на перечислениях,
длинные на главной мысли.

- Обычная сцена живёт 1,5–4 секунды. У сцены со вставкой, схемой или плашкой
  свой пол — он старше этой вилки.
- Ни одна сцена не длиннее {max_static:g} с.
- Меняй картинку между соседними сценами — положение ведущей либо вставку.
- Открывай ролик ведущей во весь кадр: первая секунда — это лицо.
- Перед кульминацией хороша сцена-передышка: ведущая крупно, без вставки.

Поле `beat` — место сцены в рассказе; переходы и вспышку код ставит по нему
сам. Значений ровно пять, и это не роли блоков сценария («cta», «payoff» и
прочие оттуда сюда не подходят):

- `hook` — первая сцена, открытие;
- `point` — обычная точка рассказа, таких большинство;
- `turn` — поворот к новой части, обычно один-три на ролик;
- `climax` — кульминация, одна на ролик и не в первой сцене;
- `outro` — финал, мягкое растворение.

## Что зритель читает

Читает он только титр, а титр строится из самой озвучки. Рубрики и пояснения
о самом ролике («вопрос первый», «фото из каталога») дублируют сказанное
голосом — в кадр их не ставь.

## Чем занять кадр: схема

**Вставка — когда мысль снимается камерой.** Действие, предмет, руки, место,
состояние человека, история из жизни.

**Схема (`schema`) — когда мысль камерой не снимается.** Ты не подписываешь
кадр, а собираешь поверх видео небольшой интерфейс, который помогает усвоить
мысль. Схема несёт саму мысль, вставка — настроение вокруг неё. Если во фразе
есть и чувство, и величина, выбирай по величине: чувство уже звучит в голосе,
а число голосом не удержать.

Форма идёт от типа высказывания, а не от того, какие слова короче.

<forms>
<form name="metric">
Крупное число с подписью; если названа база, под числом наливается полоса
`число / база` — читается как «столько из стольких».
Бери под величину: деньги, проценты, доля, срок, вес, охват, кратность —
«250 000 ₽», «87 %», «за 15 минут», «вырос вдвое», «8 из 10».
Счёт названных вещей («три вопроса», «пять правил») — это `items`: полоса
превратила бы счёт в «три из ста». Величина отвечает на «сколько чего-то»,
счёт — на «сколько штук пойдёт дальше по ролику».
Поля: `value` — начинается с цифры; `base` — целое число и только если база
названа вслух; `label` — подпись под числом.
</form>

<form name="items">
Три-четыре карточки со значком: собираются по очереди и дальше стоят.
Бери под перечисление равноправных вещей без порядка: инструменты, ошибки,
признаки, пункты разбора. Пунктов меньше трёх — это не перечисление, бери
вставку.
Карточка добавляет то, чего нет в озвучке: одиночный ярлык-существительное
(«Правила», «Скрипты») повторит слово, которое в эту секунду горит в титре.
Когда диктор анонсирует структуру («в основе три больших вопроса»), называй
сами пункты — они звучат дальше в сценарии, и ты видишь его целиком.
Поля: `items` — список из трёх-четырёх объектов `label` + `icon`.
</form>

<form name="pairs">
Строки «свойство — значение»: слева пункт, справа короткое пояснение.
Бери, когда у каждого пункта есть своя характеристика — «формат:
вертикальный», «срок: две недели». Под голое перечисление бери `items`:
правая половина обязательна, без неё в кадре тянутся пустые линии.
Поля: `rows` — список объектов `label` + `value`.
</form>

<form name="steps">
Коробки со словами, соединённые стрелками, появляются по очереди слева
направо.
Бери под порядок и причинность: «заявка → звонок → сделка», «сначала кто,
потом что, потом как». Под равноправный набор бери `items`: стрелка обещает,
что одно ведёт к другому.
Поля: `nodes` — два или три узла.
</form>

<form name="brand">
Знак названного бренда крупно, один или несколько столбиком.
Бери, когда диктор называет продукт или площадку — «Notion», «Телеграм»,
«ChatGPT». Под общее слово («нейросети», «мессенджеры») знака нет, и подбор
вернёт случайную эмблему.
Поля: `brands` — до трёх имён.
</form>
</forms>

У сцены одна форма — та, что применима больше других. В поле `why` назови тип
высказывания, к которому её отнёс: «величина», «порядок», «набор равноправных».

Если одна форма просится в половину сцен ролика — значит половина этих реплик
схемы не требует: поставь там вставку. Схема показывает то, чего камера не
берёт, и таких мест в ролике немного.

Схема показывает то, что сказано в этой сцене. Объявлен набор целиком («нужны
три вещи») — перечисли его. Названа одна позиция из набора, а остальные
прозвучат дальше — показывать в ней нечего: каждая получит свою схему там, где
её назовут.

Слова схемы говорят своё. Титр печатает реплику сам и в тот же момент, поэтому
пара слов, взятая из реплики, читается дважды. Одно общее слово — нормально;
«чем живёт» под фразой «чем живёт» — эхо.

Границы: `metric` — одно число и подпись до 28 знаков; `items` — три-четыре
карточки, подпись до 20 знаков; `pairs` — до четырёх строк, слева 22 знака,
справа 26; `steps` — до трёх узлов, коробка тем уже, чем их больше (один-два
узла держат 11 знаков, три — 8); `brand` — до трёх брендов, имя пиши как имя
(«notion», «google sheets»).

Схема живёт столько, сколько нужно её анимации: сцена короче показала бы её
недорисованной, и код такую схему снимает. Полы форм: {form_floors}.

Значки для `items`, других нет: {icon_names}.

<examples>
<example>
«Если ты устал каждый раз писать одно и то же»
Состояние человека, снимается камерой. → вставка, не схема.
</example>

<example>
«Мы вложили в это больше 250 тысяч долларов»
Величина — объём денег, а не счёт пунктов, поэтому `items` не про это, а базы
никто не называл. → `metric` без `base`.
`{{"form": "metric", "why": "величина", "value": "250 000 $",
   "label": "вложено в продукт"}}`
</example>

<example>
«А в основе лежат три больших вопроса — учим хитрые приёмы, зубрим скрипты»
Анонс структуры. «Три» здесь — счёт пунктов, а не размер чего-то, поэтому
`metric` отпадает: полоса прочтётся как «три из ста». Порядка между вопросами
нет, значит и `steps` не про это. Остаётся `items`, и число не рисуем —
называем сами пункты; ярлыки «приёмы» и «скрипты» повторили бы титр слово в
слово, поэтому каждая карточка говорит, чем занятие кончается.
`{{"form": "items", "why": "набор равноправных",
   "items": [{{"label": "приёмы без базы", "icon": "тревога"}},
             {{"label": "скрипт вместо связи", "icon": "разговор"}},
             {{"label": "фраза вместо смысла", "icon": "поиск"}}]}}`
</example>

<example>
«Сначала кто, потом что, и только потом как»
Строгий порядок. `items` обещал бы равноправие пунктов, а стрелка `steps`
обещает, что одно ведёт к другому, — здесь верно второе.
`{{"form": "steps", "why": "порядок", "nodes": ["кто", "что", "как"]}}`
</example>

<example>
«Формат вертикальный, срок две недели, правок две»
У каждого пункта своя характеристика: `items` показал бы только левую половину
и потерял значения, `steps` навязал бы порядок, которого нет. → `pairs`.
`{{"form": "pairs", "why": "характеристики пунктов",
   "rows": [{{"label": "формат", "value": "вертикальный"}},
            {{"label": "срок", "value": "две недели"}}]}}`
</example>
</examples>

## Запасная схема и плашка

**`fallback` — та же схема на случай, когда сток не ответил.** Заполняй у
сцен со вставкой, где ведущей нет: если вставка не найдётся, кадр закроет
запасная схема. Живёт по тем же правилам, что и основная.

**`overlay` — плашка каталога поверх кадра.** Ставь, когда диктор называет имя
или короткую цифру, которую стоит закрепить. Паспорта лежат в `OVERLAYS.md`
рядом с заданием: там имя блока, его слоты и пол сцены под него. Формат:
`{{"block": "имя из паспорта", "text": {{"имя слота": "строка"}}}}`. Имя блока
и ключи `text` пиши дословно из паспорта; у блока со слотами `text`
обязателен, у блока без слотов поля `text` нет. Сцена под плашку живёт не
меньше её пола из паспорта.

## Значок

`icon` — один значок поверх кадра, объект `{{"query": "английский запрос"}}`.
Уместен на сцене без ведущей и без вставки: он даёт кадру предмет. Рядом с
полнокадровой ведущей код его не ставит — там места нет.
"""


def write_montage_skill(rdir, *, positions: str, form_floors: str,
                        icon_names: str, series_min: float, series_max: float,
                        face_gap: float, max_static: float) -> Path:
    """Положить скилл с доктриной в рабочую папку прогона."""
    folder = Path(rdir) / ".claude" / "skills" / SKILL_NAME
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "SKILL.md"
    path.write_text(
        f"---\nname: {SKILL_NAME}\ndescription: {DESCRIPTION}\n---\n\n"
        + _body(positions=positions, form_floors=form_floors,
                icon_names=icon_names, series_min=series_min,
                series_max=series_max, face_gap=face_gap,
                max_static=max_static),
        encoding="utf-8")
    return path
