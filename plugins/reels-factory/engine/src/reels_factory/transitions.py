"""Световые переходы между блоками: вспышка яркости на границе + свуш.

Классический «light flash»: на границе блоков яркость кадра поднимается и
опускается треугольником за ~0.3с. Ухо цепляет свуш (кладётся выше по конвейеру,
whoosh_at), глаз — вспышку, и склейка блоков читается как задуманный переход,
а не как продолжение той же говорящей головы.

Исполнение — фильтр eq с выражением brightness от `t`: один фильтр на все
вспышки сразу (сумма треугольных термов), без лишних проходов ffmpeg. Термы вне
своего окна равны нулю, поэтому вспышки не взаимодействуют друг с другом.
"""

FLASH_DUR_S = 0.30      # полная длительность вспышки (подъём + спад)
FLASH_STRENGTH = 0.45   # пик яркости; 1.0 — чисто белый кадр, читается грубо


def build_flash_expr(times: list, dur: float = FLASH_DUR_S,
                     strength: float = FLASH_STRENGTH) -> str:
    """Выражение brightness(t): сумма треугольников вокруг каждого времени.

    Треугольник: пик strength в t=T, ноль на краях окна [T-dur/2, T+dur/2].
    max(0, ...) обнуляет терм вне окна — вспышки локальны.
    """
    half = max(0.01, dur / 2)
    terms = [f"{strength:.2f}*max(0,1-abs(t-{float(t):.3f})/{half:.3f})"
             for t in times]
    return "+".join(terms)


def build_flash_filter(times: list, dur: float = FLASH_DUR_S,
                       strength: float = FLASH_STRENGTH) -> str:
    """Строка eq-фильтра вспышек для вставки в цепочку (пустая, если нечего)."""
    if not times:
        return ""
    expr = build_flash_expr(times, dur, strength)
    # eval=frame ОБЯЗАТЕЛЕН: по умолчанию eq считает выражение один раз при
    # инициализации (t=0 -> ноль), и вспышек просто не видно
    return f"eq=brightness='{expr}':eval=frame"
